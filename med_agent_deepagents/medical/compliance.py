def classify_domain_scope(text: str, has_medical_context: bool = False) -> str:
    """以高置信规则返回 medical / smalltalk / off_topic；模糊输入返回 uncertain。"""
    normalized = str(text or "").strip()
    if not normalized:
        return "smalltalk"
    if any(pattern.fullmatch(normalized) for pattern in _SMALLTALK_PATTERNS):
        return "smalltalk"
    # 含医疗线索的混合请求先视为安全候选，交给语义安全分类判断；
    # 例如“用 Python 分析胸口不适”不能因“Python”而绕过风险识别。
    if any(pattern.search(normalized) for pattern in _MEDICAL_DOMAIN_PATTERNS):
        return "medical"
    if any(pattern.search(normalized) for pattern in _OFF_TOPIC_PATTERNS):
        return "off_topic"
    if has_medical_context and _MEDICAL_FOLLOWUP_PATTERN.fullmatch(normalized):
        return "medical"
    return "uncertain"


def detect_high_risk(text: str) -> tuple[bool, str]:
    """检测高危诉求：个人化求诊断 / 求开药。命中返回 (True, 原因)"""
    for p in _COMPILED_DIAG:
        if p.search(text):
            return True, "用户请求疾病诊断，超出能力边界"
    for p in _COMPILED_PRESC:
        if p.search(text):
            return True, "用户请求开药/用药指导，超出能力边界"
    return False, ""


def detect_emergency(text: str) -> bool:
    """检测危急症状信号（不拒绝回答，而是强制转急诊指引）"""
    return any(p.search(text) for p in _COMPILED_EMERG)


