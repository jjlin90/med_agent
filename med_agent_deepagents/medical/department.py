# 年龄通道
CHILD_AGE_LIMIT = 14
ELDER_AGE_LIMIT = 65


def recommend_departments(
    symptoms: list[str], age: int | None = None, gender: str | None = None
) -> dict:
    """根据症状列表推荐就诊科室（确定性规则，不经过大模型）

    返回: {"primary": 主科室, "alternates": 备选科室, "emergency": 是否建议急诊,
           "emergency_notice": 急诊提示文案, "matched": 命中的症状}
    """
    text = " ".join(symptoms)

    # 1. 危急信号最高优先级
    emergency_hit = [e for e in EMERGENCY_SYMPTOMS if e in text]
    if emergency_hit:
        return {
            "primary": "急诊科",
            "alternates": [],
            "emergency": True,
            "emergency_notice": "⚠ 您描述的症状可能属于急危重症，请立即前往急诊科就医，必要时拨打 120！",
            "matched": emergency_hit,
        }

    # 2. 常规科室映射：加权投票（主推荐 2 分、备选 1 分），避免多症状时按字典顺序误判
    votes: dict[str, float] = {}
    matched = []
    for kw, (dept, alts) in SYMPTOM_DEPARTMENT_MAP.items():
        if kw in text:
            matched.append(kw)
            votes[dept] = votes.get(dept, 0) + 2
            for a in alts:
                votes[a] = votes.get(a, 0) + 1

    if votes:
        ranked = sorted(votes.items(), key=lambda x: -x[1])
        primary = ranked[0][0]
        alternates = [d for d, _ in ranked[1:] if d != primary]
    else:
        primary, alternates = "全科", []

    # 3. 年龄通道调整（规则性就医指引，非诊断）
    if age is not None and age < CHILD_AGE_LIMIT and primary != "急诊科":
        alternates.insert(0, primary)
        primary = "儿科"
    if age is not None and age >= ELDER_AGE_LIMIT:
        alternates.append("老年医学科")

    # 去重保序
    seen, alts_dedup = set(), []
    for a in alternates:
        if a not in seen and a != primary:
            seen.add(a)
            alts_dedup.append(a)

    return {
        "primary": primary,
        "alternates": alts_dedup[:3],
        "emergency": False,
        "emergency_notice": "",
        "matched": matched,
    }
